// Command genroutes writes routes_gen.go from the generated tfplugin5/6
// descriptors and classes.json. It runs from internal/tfplugin via
// go generate and fails when a proto method has no class.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"

	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/compliancetf/terraform-provider-aws/internal/tfplugin"
	"github.com/compliancetf/terraform-provider-aws/internal/tfplugin/tfplugin5"
	"github.com/compliancetf/terraform-provider-aws/internal/tfplugin/tfplugin6"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("genroutes: ")

	data, err := os.ReadFile("classes.json")
	if err != nil {
		log.Fatal(err)
	}
	classes, err := tfplugin.ParseClasses(data)
	if err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/genroutes from classes.json and the tfplugin5/6 descriptors. DO NOT EDIT.\n\npackage tfplugin\n")
	tables := []struct {
		name string
		file protoreflect.FileDescriptor
	}{
		{"v5", tfplugin5.File_tfplugin5_proto},
		{"v6", tfplugin6.File_tfplugin6_proto},
	}
	seen := 0
	for _, tbl := range tables {
		routes, err := tfplugin.Build(tbl.file, classes)
		if err != nil {
			log.Fatal(err)
		}
		seen += len(routes)
		writeTable(&b, tbl.name, tbl.file.Path(), routes)
	}
	if seen != len(classes) {
		log.Fatalf("classes.json has %d entries but the pinned protos declare %d methods; remove entries for other packages", len(classes), seen)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("routes_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeTable(b *bytes.Buffer, name, path string, routes tfplugin.Routes) {
	methods := make([]string, 0, len(routes))
	for m := range routes {
		methods = append(methods, m)
	}
	slices.Sort(methods)

	fmt.Fprintf(b, "\n// %s is the route table of %s. Callers read it through a copy (V5, V6).\nvar %s = Routes{\n", name, path, name)
	for _, m := range methods {
		r := routes[m]
		class := "Passthrough"
		if r.Class == tfplugin.Intercept {
			class = "Intercept"
		}
		fmt.Fprintf(b, "%q: {FullMethod: %q, ClientStream: %t, ServerStream: %t, Class: %s},\n", m, m, r.ClientStream, r.ServerStream, class)
	}
	b.WriteString("}\n")
}
